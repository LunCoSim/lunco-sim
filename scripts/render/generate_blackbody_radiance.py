#!/usr/bin/env python3
"""Generate and check the shared GPU Planck/CIE radiance approximation.

The independent reference sums the existing 400--700 nm CIE quadrature.
Chebyshev fits approximate log(XYZ / kelvin) in reciprocal temperature;
the final interval includes infinite temperature's Rayleigh--Jeans limit.
Only the explicit GPU boundary uses float32. No third-party packages required.
"""
import argparse
import math
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[2]
DESTINATION = ROOT / 'assets/shaders/blackbody_radiance.wesl'
CMF = [(0.01431,.000396,.067850),(.13438,.004,.64560),
       (.34828,.023,1.74706),(.29080,.060,1.66920),(.09564,.13902,.81295),
       (.00490,.323,.272),(.06327,.710,.07825),(.29040,.954,.02030),
       (.59450,.995,.00390),(.91630,.870,.00165),(1.06220,.631,.00080),
       (.85445,.381,.00019),(.44790,.175,.00002),(.16490,.061,0),
       (.04677,.017,0),(.011359,.004102,0)]
DEGREE = 7
BOUNDS = [256.0 * 2**i for i in range(8)]

def reference(temperature):
    """Spectral radiance integrated into absolute CIE XYZ luminance units."""
    result = [0.0]*3
    for i, matching in enumerate(CMF):
        wavelength = (400+20*i)*1e-9
        exponent = .01438776877/(wavelength*temperature)
        spectral = 0.0 if exponent > 700 else 1.191042972e-16/(wavelength**5*math.expm1(exponent))
        weight = 683*20e-9*(.5 if i in (0,15) else 1)
        for c in range(3):
            result[c] += matching[c]*spectral*weight
    return result

def f32(x):
    return struct.unpack('f',struct.pack('f',x))[0]

def coefficients():
    result=[]
    for i, low in enumerate(BOUNDS):
        inv_low = 0.0 if i == len(BOUNDS)-1 else 1/(2*low)
        inv_high = 1/low
        values=[]
        count=64
        for j in range(count):
            theta=math.pi*(j+.5)/count
            temperature=1/(inv_low+(math.cos(theta)+1)*.5*(inv_high-inv_low))
            values.append([math.log(x/temperature) for x in reference(temperature)])
        result.append([[f32(sum(values[j][c]*math.cos(k*math.pi*(j+.5)/count) for j in range(count))
                              *(1 if k==0 else 2)/count) for c in range(3)] for k in range(DEGREE+1)])
    return result

def evaluate(temperature, tables):
    if temperature < BOUNDS[0]:
        return [0.0]*3
    band=min(int(math.log2(temperature/BOUNDS[0])),len(BOUNDS)-1)
    low=BOUNDS[band]
    inv_low=0.0 if band==len(BOUNDS)-1 else 1/(2*low)
    x=f32(f32(2*f32(f32(1/f32(temperature))-inv_low)/(1/low-inv_low))-1)
    output=[]
    for c in range(3):
        b1=b2=0.0
        for row in reversed(tables[band][1:]):
            b=f32(f32(f32(2*x)*b1)-b2+row[c]); b2,b1=b1,b
        output.append(math.exp(f32(f32(x*b1)-b2+tables[band][0][c]))*temperature)
    return output

def source(tables):
    rows=['// Generated by scripts/render/generate_blackbody_radiance.py --write.',
          '// Planck radiance + CIE 1931 quadrature; output is linear RGB in cd/m2.',
          '// Below 256 K, omitted XYZ components are each below 4e-24 cd/m2.',
          'fn blackbody_radiance(temperature: f32) -> vec3<f32> {',
          '    if temperature < 256.0 { return vec3<f32>(0.0); }',
          '    let inverse_temperature=1.0/temperature;',
          '    var xyz=vec3<f32>(0.0);']
    for i,low in enumerate(BOUNDS):
        inv_low=0 if i==len(BOUNDS)-1 else 1/(2*low)
        rows.append(('    if' if i==0 else '    } else if')+f' temperature < {2*low:.1f} {{' if i<len(BOUNDS)-1 else '    } else {')
        rows.append(f'        let x=2.0*(inverse_temperature-{inv_low:.12g})/{1/low-inv_low:.12g}-1.0;')
        rows+=['        var b1=vec3<f32>(0.0);','        var b2=vec3<f32>(0.0);']
        for row in reversed(tables[i][1:]):
            rows.append('        { let b=2.0*x*b1-b2+vec3<f32>('+','.join(f'{x:.9e}' for x in row)+'); b2=b1; b1=b; }')
        rows.append('        xyz=exp(x*b1-b2+vec3<f32>('+','.join(f'{x:.9e}' for x in tables[i][0])+'))*temperature;')
    rows+=['    }','    return max(vec3<f32>(',
           '        dot(vec3<f32>(3.2406,-1.5372,-0.4986),xyz),',
           '        dot(vec3<f32>(-0.9689,1.8758,0.0415),xyz),',
           '        dot(vec3<f32>(0.0557,-0.2040,1.0570),xyz)),vec3<f32>(0.0));','}','']
    return '\n'.join(rows)

def verify(tables):
    worst=0.0; worst_t=0.0
    temperatures=[256*math.exp(math.log(1e9/256)*i/20000) for i in range(20001)]
    temperatures += [b*(1+delta) for b in BOUNDS for delta in (-1e-6,0,1e-6)]
    for temperature in temperatures:
        if temperature<256: continue
        expected=reference(temperature); actual=evaluate(temperature,tables)
        error=max(abs(a/e-1) for a,e in zip(actual,expected))
        if error>worst: worst,worst_t=error,temperature
    assert worst<2e-4, (worst,worst_t)
    assert max(reference(256))<4e-24
    # A perturbed fit must fail the same physical comparison.
    corrupt=[[row[:] for row in table] for table in tables]
    corrupt[2][0][1]+=.05
    assert abs(evaluate(1200,corrupt)[1]/reference(1200)[1]-1)>.01
    print(f'PASS spectral reference + float32 fit + negative control: max XYZ relative error {worst:.7g} at {worst_t:.3f} K')

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write',action='store_true')
    args=parser.parse_args()
    tables=coefficients(); verify(tables); expected=source(tables)
    if args.write: DESTINATION.write_text(expected)
    else: assert DESTINATION.read_text()==expected, 'regenerate the GPU approximation'

if __name__=='__main__': main()
