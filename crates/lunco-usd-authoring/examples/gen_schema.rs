//! Publish the native schema generator's declarations for external USD tools.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

fn publish(path: &Path, content: &[u8], check: bool) -> anyhow::Result<()> {
    if check {
        anyhow::ensure!(
            std::fs::read(path)? == content,
            "{} needs regeneration",
            path.display()
        );
    } else {
        std::fs::create_dir_all(path.parent().expect("artifact directory"))?;
        std::fs::write(path, content)?;
    }
    Ok(())
}

fn main() -> anyhow::Result<()> {
    let check = match std::env::args().skip(1).collect::<Vec<_>>().as_slice() {
        [] => false,
        [flag] if flag == "--check" => true,
        _ => anyhow::bail!("usage: gen_schema [--check]"),
    };
    let package = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let root = package
        .parent()
        .and_then(Path::parent)
        .expect("workspace root");
    let schema = package.join("schema");
    let output = openusd_build::configure()
        .search_path(schema.join("bases"))
        .plug_info(schema.join("plugInfo.json"))
        .build_library(schema.join("schema.usda"), openusd_build::Views::Skip)?;
    let data = output.with_family(|family| family.to_data())?;
    let source = openusd::usda::TextWriter::write_to_string(&data)?;

    // plugInfo.json is the external plugin-manifest boundary. Declarations
    // remain native Rust values until their standard wire metadata is emitted.
    let types = output.with_family(|family| {
        family
            .schemas()
            .iter()
            .map(|decl| {
                let bases = decl
                    .declared_bases()
                    .iter()
                    .map(|base| match *base {
                        "Typed" => "UsdTyped".to_owned(),
                        "APISchemaBase" => "UsdAPISchemaBase".to_owned(),
                        name => name.to_owned(),
                    })
                    .collect::<Vec<_>>();
                let mut info = serde_json::json!({
                    "bases": bases,
                    "autoGenerated": true,
                    "schemaKind": decl.kind().as_str(),
                });
                if let Some(prefix) = decl.declared_property_namespace_prefix() {
                    info["propertyNamespacePrefix"] = serde_json::Value::String(prefix.to_owned());
                }
                (decl.identifier().to_owned(), info)
            })
            .collect::<BTreeMap<_, _>>()
    });
    let manifest = serde_json::json!({"Plugins": [{
        "Name": output.library_name(), "Type": "resource", "Root": ".",
        "ResourcePath": ".", "LibraryPath": "",
        "Info": { "SdfMetadata": {}, "Types": types },
    }]});
    let mut manifest = serde_json::to_vec_pretty(&manifest)?;
    manifest.push(b'\n');
    for directory in [schema, root.join("assets/schemas/lunco")] {
        publish(
            &directory.join("generatedSchema.usda"),
            source.as_bytes(),
            check,
        )?;
        publish(&directory.join("plugInfo.json"), &manifest, check)?;
    }
    println!(
        "native schema artifacts {}",
        if check { "verified" } else { "generated" }
    );
    Ok(())
}
